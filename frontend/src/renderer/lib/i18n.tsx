function format(message: string, vars?: TranslationVars) {
	if (!vars) return message;
	return message.replace(/\{(\w+)\}/g, (_match, key: string) =>
		Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : `{${key}}`,
	);
}

export function detectLocale(): Locale {
	if (typeof window === "undefined") return "en";
	try {
		const stored = window.localStorage.getItem(localeStorageKey);
		if (stored === "en" || stored === "zh-CN") return stored;
	} catch {
		// Use the system locale when storage is unavailable.
	}
	return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

type I18nContextValue = {
	locale: Locale;
	setLocale: (locale: Locale) => void;
	t: (message: string, vars?: TranslationVars) => string;
};

const I18nContext = createContext<I18nContextValue>({
	locale: "en",
	setLocale: () => undefined,
	t: format,
});

export function I18nProvider({ children }: { children: ReactNode }) {
	const [locale, setLocale] = useState<Locale>(detectLocale);

	useEffect(() => {
		try {
			window.localStorage.setItem(localeStorageKey, locale);
		} catch {
			// The in-memory selection still works for this session.
		}
		document.documentElement.lang = locale;
	}, [locale]);

	const value = useMemo<I18nContextValue>(
		() => ({
			locale,
			setLocale,
			t: (message, vars) => format(locale === "zh-CN" ? (zhCN[message] ?? message) : message, vars),
		}),
		[locale],
	);

	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
	return useContext(I18nContext);
}
